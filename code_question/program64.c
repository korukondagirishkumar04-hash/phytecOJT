//program to show the difference between the pre decrement and post decrement
#include<stdio.h>
int main()
{
        int i=5;
        printf("Post is %d\n",i--);
        printf("Pre is %d\n",--i);
        return 0;
}
                                                                                                     
                                                                                                     
                                                                                                     
                                                                                                     
                                                                                                     
                                                                                                     
                                                                                                     
                                        
