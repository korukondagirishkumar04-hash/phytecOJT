//program to demonstrate  bitwise OR
#include<stdio.h>
int main()
{
        //int a=20,b=30;
        //int a=5,b=3;
        int a,b;
        printf("Enter a value : ");
        scanf("%d",&a);
        printf("Enter b value : ");
        scanf("%d",&b);
        printf("a is %d\n",a);
        printf("b is %d\n",b);
        printf("OR is %d",a|b);
        return 0;
}
                                                                         
                     
