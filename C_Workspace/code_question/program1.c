//Declare variable of all basic data types and print their values
#include<stdio.h>
int main()
{
        int a=10;
        float b=10.5;
        double c=20.123456;
        char d='A';
        printf("Integer is %d\n",a);
        printf("Float is %2f\n",b);
        printf("Double is%lf\n",c);
        printf("Character is %c\n",d);
        return 0;
}

